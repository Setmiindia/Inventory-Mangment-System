"use client";

import { useActionState } from "react";
import Link from "next/link";
import { addBarcode, generateBarcode, removeBarcode, setItemActive, type FormState } from "./actions";
import { cardClass, dangerButton, inputClass, primaryButton, secondaryButton } from "@/lib/ui";

function Message({ state }: { state: FormState }) {
  if (!state) return null;
  return (
    <span role={state.ok ? "status" : "alert"} className={`text-sm font-medium ${state.ok ? "text-green-700 dark:text-green-400" : "text-[var(--danger)]"}`}>
      {state.message}
    </span>
  );
}

export function BarcodeManager({
  itemId,
  barcodes,
  canEdit,
}: {
  itemId: string;
  barcodes: { id: string; barcode: string; is_generated: boolean }[];
  canEdit: boolean;
}) {
  const [addState, addAction, adding] = useActionState<FormState, FormData>(addBarcode, null);
  const [genState, genAction, generating] = useActionState<FormState, FormData>(generateBarcode, null);
  const hasGenerated = barcodes.some((b) => b.is_generated);
  const [removeState, removeAction, removing] = useActionState<FormState, FormData>(removeBarcode, null);

  return (
    <section className={`${cardClass} max-w-5xl space-y-3 !p-5`}>
      <h2 className="text-base font-semibold">Barcodes</h2>
      {barcodes.length === 0 ? (
        <p className="text-sm text-muted">No barcode yet. Generate one, or scan the barcode printed on the product.</p>
      ) : (
        <ul className="space-y-1">
          {barcodes.map((b) => (
            <li key={b.id} className="flex items-center gap-3 text-sm">
              <code className="rounded bg-surface-muted px-2 py-0.5 font-mono">{b.barcode}</code>
              {b.is_generated && <span className="text-xs text-muted">generated by SETMI</span>}
              {/^[0-9]{13}$/.test(b.barcode) && (
                <Link href={`/items/${itemId}/labels?barcode=${b.barcode}`} className="font-medium text-[var(--brand-text)] underline">
                  Print labels
                </Link>
              )}
              {canEdit && (
                <form action={removeAction}>
                  <input type="hidden" name="id" value={b.id} />
                  <input type="hidden" name="itemId" value={itemId} />
                  <button type="submit" disabled={removing} className={secondaryButton}>Remove</button>
                </form>
              )}
            </li>
          ))}
        </ul>
      )}
      <Message state={removeState} />
      {canEdit && !hasGenerated && (
        <form action={genAction} className="flex items-center gap-3">
          <input type="hidden" name="itemId" value={itemId} />
          <button type="submit" disabled={generating} className={primaryButton}>
            {generating ? "Generating..." : "Generate barcode"}
          </button>
          <Message state={genState} />
        </form>
      )}
      {canEdit && (
        <form action={addAction} className="flex flex-wrap items-center gap-3">
          <input type="hidden" name="itemId" value={itemId} />
          <input name="barcode" required maxLength={64} placeholder="Scan or type barcode"
            aria-label="New barcode" className={`${inputClass} !mt-0 max-w-xs`} />
          <button type="submit" disabled={adding} className={primaryButton}>Add barcode</button>
          <Message state={addState} />
        </form>
      )}
    </section>
  );
}

export function ArchiveControl({ itemId, isActive }: { itemId: string; isActive: boolean }) {
  const [state, action, pending] = useActionState<FormState, FormData>(setItemActive, null);
  return (
    <section className={`${cardClass} max-w-5xl !p-5`}>
      <h2 className="text-base font-semibold">{isActive ? "Archive this product" : "Restore this product"}</h2>
      <p className="mt-0.5 text-sm text-muted">
        {isActive ? "Archiving switches the product off. Nothing is deleted and the stock history is kept." : "This product is archived. Restore it to use it again."}
      </p>
      <form action={action} className="mt-3 flex flex-wrap items-center gap-3">
        <input type="hidden" name="id" value={itemId} />
        <input type="hidden" name="active" value={isActive ? "false" : "true"} />
        <button type="submit" disabled={pending} className={isActive ? dangerButton : secondaryButton}>
          {pending ? "Please wait..." : isActive ? "Archive item" : "Restore item"}
        </button>
        <Message state={state} />
      </form>
    </section>
  );
}
